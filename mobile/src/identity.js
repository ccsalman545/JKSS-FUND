// src/identity.js
// ============================================================================
// JKSS-FUND v3.0 — LOGIN IDENTITY LAYER (single source of truth)
// ============================================================================
//
// Firebase Email/Password authentication only understands an *email-shaped*
// identifier. Students are NOT given or asked for a real email address, so
// every student username is mapped to a **synthetic identifier**:
//
//     username:     muhsin.chelakkulam
//     identifier:   muhsin.chelakkulam@students.jkss-fund.invalid
//
// The mapping is a pure, deterministic function of the username, so the same
// string is produced — with no lookup table and no network call — by:
//
//   * the mobile app (login form -> Firebase Auth),
//   * the local provisioning tool (`tools/provision`, Admin SDK), and
//   * the `users/{identifier}` Firestore document ID / ledger ownership.
//
// WHY THE `.invalid` TOP LEVEL DOMAIN
// -----------------------------------
// `.invalid` is reserved by RFC 2606 §2 and can never be registered, resolved
// or delivered to. We are therefore not "inventing a real email address", and
// a password-reset email addressed to one of these identifiers can never
// arrive at a third party (it does not exist). The app never calls
// `sendPasswordResetEmail` for student accounts (see `docs/USERNAME_LOGIN.md`
// → "Forgotten passwords"); the Admin SDK path in `tools/provision` is used
// instead.
//
// WHY THIS FILE IS COMMONJS
// -------------------------
// The Node.js test suites (`mobile/test/*.test.js`) and the provisioning tool
// (`tools/provision`) `require()` this file directly, while the React Native
// app imports it with ESM syntax (Babel interop) — exactly like the existing
// `mobile/src/accounting.js`. One implementation, three consumers: the app and
// the provisioning tool can never drift apart.
//
// SECURITY INVARIANTS (tested in mobile/test/identity.test.js)
// -----------------------------------------------------------
//   1. `identifierFor(normalizeUsername(x))` is deterministic and injective on
//      valid usernames: two different usernames can never share an identifier.
//   2. A normalized username is restricted to `[a-z0-9._-]` (no unicode, no
//      spaces, no `@`) — it can never escape the local part of the identifier
//      or forge another student's identifier.
//   3. The domain is a constant here, so an attacker cannot steer an account
//      into a domain they control.
//   4. Normalization never silently *drops* characters (dropping could merge
//      two distinct usernames into one identity); it only trims/lowercases/
//      maps whitespace to `.` and then validates.
'use strict';

/* ------------------------------------------------------------------ domain */

// RFC 2606 reserved TLD — guaranteed non-routable, never deliverable.
const STUDENT_EMAIL_DOMAIN = 'students.jkss-fund.invalid';

// Firebase Auth requires a local part < 64 chars; leave room for the domain.
const USERNAME_MAX_LENGTH = 48;
const USERNAME_MIN_LENGTH = 3;

// Letters (lowercase — usernames are case-insensitive), digits, and the three
// separator characters. No leading/trailing separator, no doubled separator
// (a `.` at the edges would produce `.user` / `user.` local parts).
const USERNAME_RE = /^[a-z0-9](?:[a-z0-9]|(?:[._-](?=[a-z0-9])))*$/;

// A deliberately conservative email shape — matches what Firebase Auth accepts
// and what the SDKs pre-validate client side.
const EMAIL_RE = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;

// Firebase's own minimum. Temp passwords generated by the provisioning tool
// are much longer (16 chars, CSPRNG) — this is the floor for *user-chosen*
// passwords in the change-password flow.
const PASSWORD_MIN_LENGTH = 6;

/* ---------------------------------------------------------- normalization  */

// Strip combining diacritics so "Muhammed Ashraf" / "Ālī" degrade to ASCII
// deterministically instead of being rejected.
function stripDiacritics(input) {
  return String(input).normalize('NFKD').replace(/[\u0300-\u036f]/g, '');
}

// Turn a display name into a base username slug.
//   "Muhsin Chelakkulam" -> "muhsin.chelakkulam"
//   "Adil Jr"            -> "adil.jr"
//   "D'Souza"            -> "dsouza"
function slugifyName(name) {
  let s = stripDiacritics(name == null ? '' : name);
  s = s.replace(/['\u2018\u2019\u02bc]/g, ''); // apostrophes vanish, not split
  s = s.toLowerCase();
  s = s.replace(/[^a-z0-9]+/g, '.'); // everything else becomes a separator
  s = s.replace(/\.{2,}/g, '.');
  s = s.replace(/[.\-_]+$/g, '').replace(/^[.\-_]+/g, '');
  return s;
}

// Canonical form of a *typed* username: trim, drop a leading '@', lowercase,
// and treat internal whitespace as a separator (so "Muhsin Chelakkulam" typed
// by a student still resolves to the assigned username). Nothing else is
// altered — invalid characters are rejected by `isValidUsername`, never
// silently removed.
function normalizeUsername(input) {
  let s = stripDiacritics(input == null ? '' : input);
  s = s.trim().toLowerCase();
  s = s.replace(/^@+/, '');
  s = s.replace(/\s+/g, '.');
  s = s.replace(/\.{2,}/g, '.');
  s = s.replace(/^[.\-_]+/, '').replace(/[.\-_]+$/, '');
  return s;
}

function isValidUsername(username) {
  const u = String(username == null ? '' : username);
  if (u.length < USERNAME_MIN_LENGTH || u.length > USERNAME_MAX_LENGTH) return false;
  return USERNAME_RE.test(u);
}

// Throwing variant used by the app/tool when a bad username should stop the
// flow with a human-readable message.
function assertUsername(username) {
  const u = normalizeUsername(username);
  if (!u) throw new Error('Enter a username');
  if (!isValidUsername(u)) {
    throw new Error(
      'Usernames use ' + USERNAME_MIN_LENGTH + '-' + USERNAME_MAX_LENGTH +
      ' characters: letters, numbers, dots, dashes and underscores ' +
      '(they must start and end with a letter or number).'
    );
  }
  return u;
}

/* --------------------------------------------------------- identifier map  */

// username -> synthetic Firebase identifier. THE mapping.
function identifierFor(username) {
  const u = assertUsername(username);
  return u + '@' + STUDENT_EMAIL_DOMAIN;
}

function isStudentIdentifier(identifier) {
  const e = String(identifier == null ? '' : identifier).trim().toLowerCase();
  if (!e.endsWith('@' + STUDENT_EMAIL_DOMAIN)) return false;
  return isValidUsername(e.slice(0, e.length - STUDENT_EMAIL_DOMAIN.length - 1));
}

// Synthetic identifier -> username (null for real emails such as the admin's).
function usernameFromIdentifier(identifier) {
  const e = String(identifier == null ? '' : identifier).trim().toLowerCase();
  if (!e.endsWith('@' + STUDENT_EMAIL_DOMAIN)) return null;
  const u = e.slice(0, e.length - STUDENT_EMAIL_DOMAIN.length - 1);
  return isValidUsername(u) ? u : null;
}

function isEmailShaped(input) {
  return EMAIL_RE.test(String(input == null ? '' : input).trim().toLowerCase());
}

// What the login form (and the provisioning tool) uses.
//   "thangal"            -> { kind: 'username', username, identifier }
//   "Admin@Jkss.in"      -> { kind: 'email',    username: 'admin', identifier: 'admin@jkss.in' }
// Admins keep signing in with their real Firebase Email/Password account;
// legacy students whose financial identity is still keyed by their real email
// (see the migration options in docs/USERNAME_LOGIN.md) sign in the same way.
function resolveLogin(input) {
  let raw = String(input == null ? '' : input).trim();
  if (!raw) throw new Error('Enter your username');

  // "@thangal" means the handle (an admin email never starts with '@').
  if (/^@+[^@]/.test(raw)) raw = raw.replace(/^@+/, '');
  if (!raw) throw new Error('Enter your username');

  if (raw.includes('@')) {
    const email = raw.toLowerCase();
    if (!isEmailShaped(email)) throw new Error('That does not look like a valid email address');
    const local = email.slice(0, email.indexOf('@'));
    return { kind: 'email', input: raw, identifier: email, username: normalizeUsername(local) };
  }

  const username = normalizeUsername(raw);
  if (!username) throw new Error('Enter your username');
  if (!isValidUsername(username)) {
    throw new Error(
      'Usernames use letters, numbers, dots, dashes and underscores — ' +
      'check the username your admin gave you.'
    );
  }
  return { kind: 'username', input: raw, identifier: identifierFor(username), username };
}

// Display handle for a profile/document ID.
function displayUsername(identifier) {
  const u = usernameFromIdentifier(identifier);
  if (u) return u;
  const e = String(identifier == null ? '' : identifier).toLowerCase();
  const at = e.indexOf('@');
  return at > 0 ? e.slice(0, at) : e;
}

/* -------------------------------------------------------- roster planning  */

// Deterministic roster -> username assignment with collision resolution.
//
//   assignUsernames(['Adil', 'Adil', 'Adil 2'])
//     -> adil, adil.2, adil.2.2   (roster order decides; stable for reruns)
//
// The FIRST entry (by roster order) of a colliding group keeps the plain slug;
// every later one receives the smallest `.N` suffix (N >= 2) that is still
// free. Because the algorithm walks the roster in order and only ever appends
// free names, it is deterministic: the same roster always yields the same
// usernames, which is what keeps Auth identifiers, profile doc IDs and ledger
// ownership stable across provisioning reruns.
//
// `entries` accepts plain strings or `{ name, username? }` objects; an explicit
// `username` override is honored verbatim (after validation) and reserved, so
// no other entry can collide with it.
function assignUsernames(entries) {
  if (!Array.isArray(entries)) throw new Error('assignUsernames expects an array');
  const used = new Set();
  const out = [];

  // Pass 1 — explicit overrides first (they always win, regardless of order).
  const items = entries.map((entry, index) => {
    if (typeof entry === 'string') return { index, name: entry, username: null };
    const name = entry && (entry.name != null ? String(entry.name) : '');
    const override = entry && entry.username != null ? String(entry.username) : null;
    return { index, name, username: override };
  });

  for (const it of items) {
    if (!it.username) continue;
    const u = assertUsername(it.username);
    if (used.has(u)) {
      throw new Error(
        'Duplicate explicit username "' + u + '" — assigned usernames must be unique ' +
        '(roster position ' + (it.index + 1) + ')'
      );
    }
    used.add(u);
    it.resolved = u;
    it.source = 'assigned';
  }

  // Pass 2 — derive the rest in roster order.
  for (const it of items) {
    if (it.resolved) continue;
    if (!stripDiacritics(it.name).trim()) {
      throw new Error('Roster entry ' + (it.index + 1) + ' has no usable name');
    }
    const base = slugifyName(it.name);
    if (!isValidUsername(base)) {
      throw new Error(
        'Cannot derive a username from "' + it.name + '" (roster position ' +
        (it.index + 1) + ') — give it an explicit "username" in roster.json'
      );
    }

    let candidate = base;
    if (used.has(candidate)) {
      // Deterministic disambiguation: smallest free ".N" (N from 2 upward).
      let n = 2;
      let next = base + '.' + n;
      while (used.has(next) || !isValidUsername(next)) {
        n += 1;
        next = base + '.' + n;
        if (n > 999) {
          throw new Error(
            'Cannot resolve a unique username for "' + it.name + '" — ' +
            'set an explicit "username" in roster.json'
          );
        }
      }
      candidate = next;
    }
    if (!isValidUsername(candidate)) {
      throw new Error('Derived an invalid username from "' + it.name + '"');
    }
    used.add(candidate);
    it.resolved = candidate;
    it.source = candidate === base ? 'derived' : 'derived+collision';
  }

  // Emit in roster order (items[] is already ordered by index).
  for (const it of items) {
    const base = slugifyName(it.name);
    out.push({
      index: it.index,
      name: it.name,
      username: it.resolved,
      base,
      source: it.source,
      collided: it.source !== 'derived',
      identifier: identifierFor(it.resolved),
    });
  }
  return out;
}

/* ---------------------------------------------------------- password policy */

// Policy for *user-chosen* passwords (change-password flow). The provisioning
// tool's generated passwords satisfy this by a wide margin.
function validatePasswordPolicy(password, { username, name } = {}) {
  const pw = String(password == null ? '' : password);
  if (pw.length < PASSWORD_MIN_LENGTH) {
    return { ok: false, reason: 'Password must be at least ' + PASSWORD_MIN_LENGTH + ' characters' };
  }
  if (pw.length > 4096) return { ok: false, reason: 'Password is too long' };
  if (!/[A-Za-z]/.test(pw) || !/[0-9]/.test(pw)) {
    return { ok: false, reason: 'Password must contain at least one letter and one number' };
  }

  const lowered = pw.toLowerCase();
  const flat = lowered.replace(/[^a-z0-9]/g, '');
  const containsIdentity = (needle) => {
    const n = needle.replace(/[^a-z0-9]/g, '');
    if (n.length < 4) return false;
    return flat === n || flat.includes(n);
  };

  const u = username ? normalizeUsername(username) : '';
  if (containsIdentity(u)) {
    return { ok: false, reason: 'Password cannot contain your username' };
  }
  const n = name ? slugifyName(name) : '';
  if (containsIdentity(n)) {
    return { ok: false, reason: 'Password cannot contain your name' };
  }
  if (/^(password|123456|qwerty|admin)$/i.test(pw)) {
    return { ok: false, reason: 'Password is too common' };
  }
  return { ok: true };
}

